package com.clawkit.ops.loop.repair;

import com.clawkit.tools.ToolRiskLevel;
import com.clawkit.tools.action.ActionDescriptor;
import com.clawkit.tools.action.ActionReliability;
import com.clawkit.tools.action.Reversibility;
import com.clawkit.tools.action.VerificationMode;

import java.util.List;
import java.util.Objects;
import java.util.Set;

/**
 * Fixed allowed repair action definition.
 *
 * <p>MVP-3 supports exactly one action: {@code restart_service(serviceId=order-api)}.
 * Each action declares its contract, preconditions, expected effects,
 * and compensation strategy up-front — not generated by the model at runtime.
 *
 * <p>This type is NOT an {@link ActionDescriptor}; it is the declarative template
 * from which a descriptor is built for a specific incident, target, and snapshot.
 */
public record RepairAction(
    String actionCode,
    Set<String> allowedServiceIds,
    int maxExecutions,
    List<String> preconditions,
    List<String> expectedEffects,
    String compensationSummary,
    String blastRadius
) {
    /** The only action allowed in MVP-3. */
    public static final RepairAction RESTART_SERVICE = new RepairAction(
        "restart_service",
        Set.of("order-api"),
        1,
        List.of(
            "service_status reports order-api as down or exited",
            "container_status reports order-api as stopped or unhealthy",
            "http_probe to /ready returns non-200 or connection refused"
        ),
        List.of(
            "order-api container is running",
            "order-api /ready returns 200",
            "order-api business endpoint returns valid response"
        ),
        "restart_service is compensatable: if the restart causes new errors, "
            + "the service can be stopped again and escalated to manual investigation",
        "Single container: order-api. Does not affect postgres, gateway, or k6."
    );

    public RepairAction {
        Objects.requireNonNull(actionCode, "actionCode required");
        Objects.requireNonNull(allowedServiceIds, "allowedServiceIds required");
        if (allowedServiceIds.isEmpty()) throw new IllegalArgumentException("allowedServiceIds must not be empty");
        if (maxExecutions < 1) throw new IllegalArgumentException("maxExecutions must be >= 1");
        preconditions = List.copyOf(preconditions);
        expectedEffects = List.copyOf(expectedEffects);
        if (compensationSummary == null) compensationSummary = "";
        if (blastRadius == null) blastRadius = "";
    }

    /** Build a P1-G ActionDescriptor for a specific target, service, and evidence snapshot. */
    public ActionDescriptor toActionDescriptor(String canonicalTarget, String serviceId,
                                                String snapshotHash) {
        if (!allowedServiceIds.contains(serviceId)) {
            throw new IllegalArgumentException(
                "serviceId '" + serviceId + "' not in allowed set: " + allowedServiceIds);
        }
        return new ActionDescriptor(
            actionCode,
            canonicalTarget,
            "serviceId=" + serviceId + " snapshot=" + snapshotHash,
            ToolRiskLevel.HIGH,
            Reversibility.COMPENSATABLE,
            ActionReliability.none(),  // remote action: no client-side idempotency guarantee
            VerificationMode.WORKFLOW,  // verified by IndependentVerifier workflow
            preconditions,
            expectedEffects,
            compensationSummary,
            blastRadius
        );
    }
}
